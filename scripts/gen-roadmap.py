#!/usr/bin/env python3
"""Regenerates the roadmap blocks of README.md and ROADMAP.md from what the repository itself says.

Sources (nothing is typed twice):
  VERSION                      the current release and its stage
  docs/product/08-phases.md    the phase table: pain, scope, state
  CHANGELOG.md                 the latest releases and what each one brought
  VERSIONS.md                  the contract and schema numbers

The blocks live between <!-- roadmap:start --> and <!-- roadmap:end --> in each file; everything outside them is hand-written
and is never touched. `--check` exits 1 when a file is out of date (CI), without writing.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- roadmap:start -->", "<!-- roadmap:end -->"
RELEASES = 6          # releases listed
TITLES_PER_RELEASE = 4


def read(name: str) -> str:
    return (ROOT / name).read_text(encoding="utf-8")


def version() -> str:
    return read("VERSION").strip()


def stage(v: str) -> str:
    m = re.search(r"-(alpha|beta|rc)", v)
    return m.group(1) if m else "stable"


def versions_table() -> dict:
    out = {}
    for line in read("VERSIONS.md").splitlines():
        m = re.match(r"\|\s*`(contract/api|data/db-schema)`\s*\|\s*([^|]+?)\s*\|", line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def phases() -> list:
    rows = []
    for line in read("docs/product/08-phases.md").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 4 and cells[0].isdigit():
            rows.append(cells)
    return rows


WORDS = {"\u2705": "Done \u00b7", "\U0001F6A7": "In progress \u00b7", "\U0001F5D3": "Planned \u00b7"}  # check mark, construction, calendar
EMOJI = re.compile("[\u2600-\u27BF\U0001F000-\U0001FAFF\uFE0F\u200D]")


def plain(text: str) -> str:
    """The README carries no emoji: the status marks of the phases file become words, any other pictograph is dropped."""
    for mark, word in WORDS.items():
        text = text.replace(mark + "\uFE0F", word).replace(mark, word)
    return re.sub(r"\s+", " ", EMOJI.sub("", text)).strip()


def short(text: str, limit: int = 150) -> str:
    """One line: links reduced to their text, cut at a word (or a ';') before the limit."""
    text = plain(re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)).replace("|", "/")
    if len(text) <= limit:
        return text
    cut = text[:limit]
    at = max(cut.rfind("; "), cut.rfind(". "), cut.rfind(", "))
    cut = cut[:at] if at > limit * 0.55 else cut[: cut.rfind(" ")]
    return cut.rstrip(" ;,.") + "…"


def releases() -> list:
    text = read("CHANGELOG.md")
    out = []
    for m in re.finditer(r"^## \[([^\]]+)\]\s*-\s*([\d-]+)\s*$(.*?)(?=^## \[|\Z)", text, flags=re.M | re.S):
        ver, date, body = m.group(1), m.group(2), m.group(3)
        titles = [t.strip().rstrip(".") for t in re.findall(r"^- \*\*(.+?)\*\*", body, flags=re.M)]
        out.append((ver, date, titles))
        if len(out) >= RELEASES:
            break
    return out


def block() -> str:
    v = version()
    ver = versions_table()
    lines = [
        START,
        f"<!-- generated by scripts/gen-roadmap.py from VERSION, CHANGELOG.md and docs/product/08-phases.md: do not edit between the markers -->",
        "",
        f"**Now:** `{v}` · stage **{stage(v)}** · API contract `{ver.get('contract/api', '?')}` · schema migration `{ver.get('data/db-schema', '?')}`",
        "",
        "| Phase | The pain it answers | State |",
        "|---|---|---|",
    ]
    for cells in phases():
        n, pain, _scope, state = cells[0], cells[1], cells[2], cells[3]
        lines.append(f"| {n} | {short(pain, 90)} | {short(state, 200)} |")
    lines += ["", "**Latest releases**", ""]
    for ver_, date, titles in releases():
        shown = titles[:TITLES_PER_RELEASE]
        more = len(titles) - len(shown)
        text = "; ".join(shown) + (f"; … and {more} more" if more > 0 else "") if shown else "maintenance"
        lines.append(f"- **{ver_}** ({date}): {text}")
    lines += ["", END]
    return "\n".join(lines)


def apply(path: str, generated: str) -> str:
    text = read(path)
    if START not in text or END not in text:
        raise SystemExit(f"{path}: markers {START} / {END} are missing")
    head = text.split(START)[0]
    tail = text.split(END, 1)[1]
    return head + generated + tail


def main() -> int:
    check = "--check" in sys.argv
    generated = block()
    stale = []
    for path in ("README.md", "ROADMAP.md"):
        new = apply(path, generated)
        if new != read(path):
            stale.append(path)
            if not check:
                (ROOT / path).write_text(new, encoding="utf-8")
    if stale and check:
        print("out of date: " + ", ".join(stale) + " (run: make roadmap)")
        return 1
    print("roadmap " + ("is current" if not stale else "updated: " + ", ".join(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main())

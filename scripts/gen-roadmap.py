#!/usr/bin/env python3
"""Regenerates the roadmap blocks of README.md and ROADMAP.md from what the repository itself says.

Sources (nothing is typed twice):
  VERSION                      the current release and its stage
  docs/product/08-phases.md    the phase table: pain, scope, state
  CHANGELOG.md                 the latest releases and what each one brought
  VERSIONS.md                  the contract and schema numbers

The roadmap blocks live between <!-- roadmap:start --> and <!-- roadmap:end --> in README.md (Ukrainian), README.en.md and
ROADMAP.md. README.md also carries the whole platform description between <!-- architecture:start --> and <!-- architecture:end -->,
copied from docs/architecture/platform-full.uk.md with its relative links rewritten, so the README shows the description itself
instead of pointing at a file. Everything outside the markers is hand-written and is never touched.
`--check` exits 1 when a file is out of date (CI), without writing.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- roadmap:start -->", "<!-- roadmap:end -->"
A_START, A_END = "<!-- architecture:start -->", "<!-- architecture:end -->"

TEXT = {
    "en": {"now": "Now", "stage": "stage", "contract": "API contract", "schema": "schema migration",
           "head": ("Phase", "The pain it answers", "State"), "latest": "Latest releases", "more": "… and {n} more",
           "maintenance": "maintenance", "words": {"\u2705": "Done \u00b7", "\U0001F6A7": "In progress \u00b7", "\U0001F5D3": "Planned \u00b7"}},
    "uk": {"now": "Зараз", "stage": "стадія", "contract": "контракт API", "schema": "міграція схеми",
           "head": ("Фаза", "Яку біль закриває", "Стан"), "latest": "Останні релізи", "more": "… і ще {n}",
           "maintenance": "супровід", "words": {"\u2705": "Готово \u00b7", "\U0001F6A7": "У роботі \u00b7", "\U0001F5D3": "Заплановано \u00b7"}},
}
TARGETS = {"README.md": "uk", "README.en.md": "en", "ROADMAP.md": "en"}
LANG = ["en"]  # the language of the block being built (short() reads it)
RELEASES = 6          # releases listed
TITLES_PER_RELEASE = 4


def read(name: str) -> str:
    return (ROOT / name).read_text(encoding="utf-8")


def version() -> str:
    return read("VERSION").strip()


def stage(v: str) -> str:
    m = re.search(r"-(alpha|beta|rc)", v)
    return m.group(1) if m else "stable"


def versions_table() -> dict:
    out = {}
    for line in read("VERSIONS.md").splitlines():
        m = re.match(r"\|\s*`(contract/api|data/db-schema)`\s*\|\s*([^|]+?)\s*\|", line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def phases() -> list:
    rows = []
    for line in read("docs/product/08-phases.md").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 4 and cells[0].isdigit():
            rows.append(cells)
    return rows


# status marks of the phases file: check mark, construction, calendar
EMOJI = re.compile("[\u2600-\u27BF\U0001F000-\U0001FAFF\uFE0F\u200D]")


def plain(text: str) -> str:
    """The README carries no emoji: the status marks of the phases file become words, any other pictograph is dropped."""
    for mark, word in TEXT[LANG[0]]["words"].items():
        text = text.replace(mark + "\uFE0F", word).replace(mark, word)
    return re.sub(r"\s+", " ", EMOJI.sub("", text)).strip()


def short(text: str, limit: int = 150) -> str:
    """One line: links reduced to their text, cut at a word (or a ';') before the limit."""
    text = plain(re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)).replace("|", "/")
    if len(text) <= limit:
        return text
    cut = text[:limit]
    at = max(cut.rfind("; "), cut.rfind(". "), cut.rfind(", "))
    cut = cut[:at] if at > limit * 0.55 else cut[: cut.rfind(" ")]
    return cut.rstrip(" ;,.") + "…"


def releases() -> list:
    text = read("CHANGELOG.md")
    out = []
    for m in re.finditer(r"^## \[([^\]]+)\]\s*-\s*([\d-]+)\s*$(.*?)(?=^## \[|\Z)", text, flags=re.M | re.S):
        ver, date, body = m.group(1), m.group(2), m.group(3)
        titles = [t.strip().rstrip(".") for t in re.findall(r"^- \*\*(.+?)\*\*", body, flags=re.M)]
        out.append((ver, date, titles))
        if len(out) >= RELEASES:
            break
    return out


def block(lang: str) -> str:
    LANG[0] = lang
    t = TEXT[lang]
    v = version()
    ver = versions_table()
    lines = [
        START,
        "<!-- generated by scripts/gen-roadmap.py from VERSION, CHANGELOG.md and docs/product/08-phases.md: do not edit between the markers -->",
        "",
        f"**{t['now']}:** `{v}` · {t['stage']} **{stage(v)}** · {t['contract']} `{ver.get('contract/api', '?')}` · {t['schema']} `{ver.get('data/db-schema', '?')}`",
        "",
        f"| {t['head'][0]} | {t['head'][1]} | {t['head'][2]} |",
        "|---|---|---|",
    ]
    for cells in phases():
        n, pain, _scope, state = cells[0], cells[1], cells[2], cells[3]
        lines.append(f"| {n} | {short(pain, 90)} | {short(state, 200)} |")
    lines += ["", f"**{t['latest']}**", ""]
    for ver_, date, titles in releases():
        shown = titles[:TITLES_PER_RELEASE]
        more = len(titles) - len(shown)
        text = "; ".join(shown) + (f"; {t['more'].format(n=more)}" if more > 0 else "") if shown else t["maintenance"]
        lines.append(f"- **{ver_}** ({date}): {text}")
    lines += ["", END]
    return "\n".join(lines)


LINKS = [  # relative links of docs/architecture/platform-full.uk.md, as they must read from the repository root
    ("](../../", "]("), ("](../adr/", "](docs/adr/"), ("](../security/", "](docs/security/"), ("](../product/", "](docs/product/"),
    ("](../operations/", "](docs/operations/"), ("](../setup/", "](docs/setup/"), ("](overview.md", "](docs/architecture/overview.md"),
    ("](platform-architecture.md", "](docs/architecture/platform-architecture.md"),
]


DOC = "docs/architecture/platform-full.uk.md"
DOC_VERSION = re.compile(r"(відповідає релізу `)[^`]+(`)")


def doc_text() -> str:
    """The description names the release it matches: kept equal to VERSION so it never says an old number."""
    return DOC_VERSION.sub(lambda m: m.group(1) + version() + m.group(2), read(DOC))


def architecture() -> str:
    body = doc_text()
    body = body.split("\n", 1)[1] if body.startswith("# ") else body  # the README has its own title
    for old, new in LINKS:
        body = body.replace(old, new)
    # the document's own sections become sections of the README: one level down would nest them under "Повний опис", they stay as they are
    return "\n".join([A_START, "<!-- generated from docs/architecture/platform-full.uk.md: edit that file -->", body.strip("\n"), "", A_END])


def replace_between(text: str, start: str, end: str, generated: str, path: str) -> str:
    if start not in text or end not in text:
        raise SystemExit(f"{path}: markers {start} / {end} are missing")
    return text.split(start)[0] + generated + text.split(end, 1)[1]


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    if doc_text() != read(DOC):
        stale.append(DOC)
        if not check:
            (ROOT / DOC).write_text(doc_text(), encoding="utf-8")
    for path, lang in TARGETS.items():
        old = read(path)
        new = replace_between(old, START, END, block(lang), path)
        if path == "README.md":
            new = replace_between(new, A_START, A_END, architecture(), path)
        if new != old:
            stale.append(path)
            if not check:
                (ROOT / path).write_text(new, encoding="utf-8")
    if stale and check:
        print("out of date: " + ", ".join(stale) + " (run: make roadmap)")
        return 1
    print("roadmap " + ("is current" if not stale else "updated: " + ", ".join(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
